#!/usr/bin/env python3
"""Collect Waxbill's user-visible strings into Design/copy/ui-strings.md for a wording review.

Finds t("中文", "English") calls and ("中文", "English") pairs (the specs in screens/simple.rs), and lists the
Chinese lines of format! branches, which are written per language. Run from the repository root:

    python3 scripts/ui-strings.py
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LITERAL = r'"((?:[^"\\]|\\.)*)"'
PAIR = re.compile(r'(?:\bt\(|\()\s*' + LITERAL + r'\s*,\s*' + LITERAL + r'\s*,?\s*\)', re.S)
CJK = re.compile(r'[一-鿿]')
CHINESE_BRANCH = re.compile(r'Language::Chinese\s*=>\s*(?:\{\s*)?format!\(\s*' + LITERAL, re.S)

# The screen each file belongs to, in sidebar order.
SECTIONS = [
    ("Shell, run bar and results", ["app.rs", "run.rs", "run_bar.rs", "results.rs", "run_dialogs.rs",
                                    "conflicts.rs", "id_species.rs", "runner.rs"]),
    ("标签读取 observe", ["screens/observe.rs"]),
    ("独立捕获 capture", ["screens/capture.rs"]),
    ("查看媒体 browse", ["browse/mod.rs", "browse/records.rs", "browse/review.rs"]),
    ("XMP 更新 update", ["screens/update.rs"]),
    ("媒体提取 extract", ["screens/extract.rs"]),
    ("Spec-driven screens: XMP 初始化, 元数据同步, XMP 导出, 重命名, 路径对齐, XMP 删除", ["screens/simple.rs"]),
    ("物种名替换 translate", ["screens/translate.rs"]),
    ("Shared form pieces", ["screens/form.rs", "screens/mod.rs"]),
    ("Table check and repair", ["repair.rs", "table.rs"]),
    ("Settings", ["settings_screen.rs", "serval.rs", "caracal.rs", "bridge.rs"]),
]


def unescape(text: str) -> str:
    return text.replace('\\"', '"').replace("\\n", " ").replace("|", "\\|")


def rows(path: Path):
    source = path.read_text(encoding="utf-8")
    line_of = lambda offset: source.count("\n", 0, offset) + 1
    seen = set()
    for match in PAIR.finditer(source):
        zh, en = match.group(1), match.group(2)
        if CJK.search(zh) and (zh, en) not in seen:
            seen.add((zh, en))
            yield line_of(match.start()), unescape(zh), unescape(en)
    for match in CHINESE_BRANCH.finditer(source):
        zh = match.group(1)
        if CJK.search(zh) and (zh, "") not in seen:
            seen.add((zh, ""))
            yield line_of(match.start()), unescape(zh), "(format!, written per language)"
    # Any other Chinese literal outside comments and tests: pieces of sentences, example data.
    known = {zh for zh, _ in seen}
    body = source.split("#[cfg(test)]")[0]
    body = re.sub(r"//[^\n]*", lambda m: " " * len(m.group(0)), body)
    for match in re.finditer(LITERAL, body):
        text = match.group(1)
        if CJK.search(text) and text not in known:
            known.add(text)
            yield line_of(match.start()), unescape(text), "(fragment)"


def main():
    src = ROOT / "src"
    covered = set()
    out = [
        "# UI wording",
        "",
        "Generated by `scripts/ui-strings.py` from the source: every Chinese string with its English twin and where",
        "it is. Mark changes here (or in comments); they are then made in the code. Strings built with `format!`",
        "per language are listed by their Chinese line only; \"(fragment)\" marks a piece of a longer sentence or",
        "example data.",
        "",
    ]
    total = 0
    for title, files in SECTIONS:
        out += [f"## {title}", "", "| 中文 | English | Where |", "| --- | --- | --- |"]
        for name in files:
            path = src / name
            if not path.exists():
                continue
            covered.add(path)
            for line, zh, en in rows(path):
                out.append(f"| {zh} | {en} | `{name}:{line}` |")
                total += 1
        out.append("")
    rest = [p for p in sorted(src.rglob("*.rs")) if p not in covered and any(True for _ in rows(p))]
    if rest:
        out += ["## Other", "", "| 中文 | English | Where |", "| --- | --- | --- |"]
        for path in rest:
            for line, zh, en in rows(path):
                out.append(f"| {zh} | {en} | `{path.relative_to(src)}:{line}` |")
                total += 1
        out.append("")
    target = ROOT / "Design" / "copy" / "ui-strings.md"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(out), encoding="utf-8")
    print(f"{total} strings → {target.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
